    private static ControlDocsPage InputPage(
        string type,
        string title,
        string summary,
        IReadOnlyList<string> useWhen,
        IReadOnlyList<string> avoidWhen,
        IReadOnlyList<ControlDocsAlternative> alternatives,
        string usage,
        string anatomy,
        string variants,
        string stateOwnership,
        string pointerInteraction,
        IReadOnlyList<ControlDocsKeyboardBinding> keyboard,
        string focusActivationDismissal,
        ControlDocsAccessibility accessibility,
        ControlDocsThemeLayout themeLayout,
        ControlDocsConstraints constraints,
        string api,
        string apiHighlights,
        string eventContracts,
        IReadOnlyList<ControlDocsStory>? related = null)
    {
        string prefix = $"Controls/Input/{api}";
        var relatedStories = new List<ControlDocsStory>
